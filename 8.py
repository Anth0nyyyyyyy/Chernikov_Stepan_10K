a = int(input())
b = int(input())
print("Сумма:", a, "+", b, "=", a+b)
print("Разность:", a, "-", b, "=", a-b)
print(f"Произведение: {a} * {b} = {a * b}")
print(f"Деление: {a} / {b} = {a / b:.2f}")
print("Целочисленное деление:", a, "//", b, "=", a//b)
print("Остаток от деления:", a, "%", b, "=", a%b)
print("Возведение в степень:", a, "**", b, "=", a**b)
